bool scene_machine_form_takes(Snes *s, void (*entry)(Snes *))
{
    for (unsigned i = 0; i < sizeof forms / sizeof forms[0]; i++) {
        if (forms[i].entry != entry)
            continue;
        if (!s->cpu.e && (s->cpu.p & forms[i].mask) == forms[i].value &&
            (!forms[i].takes || forms[i].takes(s)))
            return true;
        program_breaks_a_contract(state_of(s), forms[i].address, "a scene call outside its contract");
        return false;
    }
    return false;
}
