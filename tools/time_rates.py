"""The calibrated rates, for a build with no machine: every registered entry's
and time tag's cost_milli, written as a C table the native program's time
model looks a tag up in (runtime/port/state_host.c, docs/REIMPLEMENTATION.md,
"The frame-level time model").

    python3 tools/time_rates.py game/registry.c game/time_tags.c -o build/time_rates.c

The build runs it (CMakeLists.txt), so the table is always the registry's as
tools/timing_gate.py last calibrated it: the program has no registry of its
own, and the rates are the estimates the machine measured, read where the
calibration writes them. Entries are parsed as timing_gate.calibrate rewrites
them: `{ .addr = 0x..., ..., .cost_milli = N, ... }` or a table macro's
`MACRO(0x..., name, N)`. An address given twice keeps its first rate, as the
runtime's lookup finds the first entry.
"""

import argparse
import pathlib
import re
import sys

STRUCT = re.compile(r"\{ \.addr = (0x[0-9A-Fa-f]+),.*?\}(?=,)", re.S)
COST = re.compile(r"\.cost_milli = (\d+)")
MACRO = re.compile(r"^    [A-Z_]+\((0x[0-9A-Fa-f]+), \w+, (\d+)(?:, \w+)*\)", re.M)


def rates(text):
    """[(addr, cost_milli)] in the order the source gives them."""
    found = []
    for m in STRUCT.finditer(text):
        cm = COST.search(m.group(0))
        if cm:
            found.append((m.start(), int(m.group(1), 16), int(cm.group(1))))
    for m in MACRO.finditer(text):
        found.append((m.start(), int(m.group(1), 16), int(m.group(2))))
    return [(a, c) for _, a, c in sorted(found)]


def table(sources):
    seen = {}
    for text in sources:
        for addr, cost in rates(text):
            seen.setdefault(addr & 0xFFFFFF, cost)
    return sorted(seen.items())


def write(rows, out):
    lines = ["/* Generated by tools/time_rates.py from game/registry.c and game/time_tags.c: do not edit. */",
             '#include "port/time_rates.h"', "",
             "const TimeRate time_rates[] = {"]
    lines += ["    { 0x%06X, %d }," % (a, c) for a, c in rows] or ["    { 0, 0 },"]
    lines += ["};", "const unsigned time_rate_count = %d;" % len(rows), ""]
    out.write_text("\n".join(lines), newline="\n")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python3 tools/time_rates.py")
    ap.add_argument("sources", nargs="+", type=pathlib.Path)
    ap.add_argument("-o", "--out", type=pathlib.Path, required=True)
    args = ap.parse_args(argv)
    rows = table([p.read_text() for p in args.sources])
    if not rows:
        sys.exit("no rates found in %s" % ", ".join(map(str, args.sources)))
    write(rows, args.out)


if __name__ == "__main__":
    main()
