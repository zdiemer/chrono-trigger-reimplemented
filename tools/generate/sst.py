"""Generate C that runs SingleStepTests cases through translated instructions.

    python3 -m tools.generate.sst --out build/main/generated_sst

Writes one function per opcode and register context (m8x8, m8x16, m16x8,
m16x16, emu), each the translation of that opcode with its operand bytes, PC and
program bank read at run time, plus the table sst_generated_runner and
generated_bus_diff dispatch through (CMakeLists.txt runs this). Nothing here comes
from the ROM, but it is generated: it stays in the build tree.
"""

import argparse
from pathlib import Path

from tools.disasm.cpu import OPCODES, operand_size

from .translate import Ctx, Operand, add16, addr24, indent, lit, translate

# Table order; sst_runner.c computes the same index from P and E.
CONTEXTS = [Ctx(True, True), Ctx(True, False), Ctx(False, True), Ctx(False, False), Ctx(True, True, True)]
FILES = 16


class ReturnFlow:
    """Every control transfer leaves the function: one instruction per call."""

    def jump(self, pc, pb=None):
        out = [] if pb is None else [f"c->pb = {lit(pb, 2)};"]
        return out + [f"c->pc = {lit(pc, 4)};", "return;"]

    def exit(self):
        return ["return;"]


def function_name(opcode: int, ctx: Ctx) -> str:
    return f"sst_generated_{opcode:02x}_{ctx.name()}"


def function(opcode: int, ctx: Ctx) -> list[str]:
    name, mode = OPCODES[opcode]
    n = operand_size(mode, ctx.m8, ctx.x8)
    operand = Operand(tuple(f"b{i}" for i in range(1, n + 1)))
    t = translate(opcode, operand, "pc", "pb", ctx, ReturnFlow())
    body = ["const uint16_t pc = c->pc;", "const uint8_t pb = c->pb;"]
    body += [f"const uint8_t b{i} = SST_PEEK(c, {addr24('pb', add16('pc', i))});" for i in range(1, n + 1)]
    body += t.lines
    if t.falls_through:
        body.append(f"c->pc = {add16('pc', t.size)};")
    return [f"/* {name} ({mode.value}), {ctx.name()} */", f"void {function_name(opcode, ctx)}(Cpu *c)", "{",
            *indent(body), "}", ""]


def generate(out: Path):
    out.mkdir(parents=True, exist_ok=True)
    header = ["/* Generated by tools/generate/sst.py. Do not edit. */", '#include "sst_generated.h"', ""]
    for f in range(FILES):
        lines = list(header)
        for opcode in range(f * 256 // FILES, (f + 1) * 256 // FILES):
            for ctx in CONTEXTS:
                lines += function(opcode, ctx)
        write(out / f"ops_{f:x}.c", lines)
    table = list(header)
    table += [f"void {function_name(op, ctx)}(Cpu *c);" for op in range(256) for ctx in CONTEXTS]
    table += ["", "const SstGeneratedFn sst_generated_table[256][5] = {"]
    for op in range(256):
        table.append("    { " + ", ".join(function_name(op, ctx) for ctx in CONTEXTS) + " },")
    table += ["};"]
    write(out / "table.c", table)


def write(path: Path, lines: list[str]):
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser(prog="python3 -m tools.generate.sst")
    ap.add_argument("--out", type=Path, required=True)
    generate(ap.parse_args().out)


if __name__ == "__main__":
    main()
