"""Generate C blocks for every statically found code block of the ROM.

    python3 -m tools.generate --rom roms/ct-usa.sfc --out build/main/generated \\
        [--hints re/hints.toml] [--registry game/registry.c] \\
        [--coverage traces/coverage.txt ...] [--calls traces/calls.txt ...] [--shards 64]

Runs the disassembler's analysis in process (hints, coverage seeds), forms
blocks (tools/generate/blocks.py) and writes blocks_000.c ... blocks_NNN.c and
table.c into --out. Output is ROM-derived: it belongs in the build tree only.
Files whose content didn't change aren't rewritten, so the build only
recompiles what changed. See docs/GENERATED.md.
"""

import argparse
import re
import sys
import time
import zlib
from pathlib import Path

from tools.disasm import coverage as coverage_mod
from tools.disasm import hints as hints_mod
from tools.disasm.analyze import Analyzer
from tools.disasm.closure import code_set
from tools.disasm.memmap import Rom, bus_to_offset

from .blocks import BlockBuilder
from .translate import indent

ROM_CRC32 = 0x2D206BF7
HEADER = ["/* Generated by tools/generate from the ROM (docs/GENERATED.md). ROM-derived: never commit. */"]


def registry_addresses(path: Path) -> set:
    """Every 24-bit ROM or work RAM address named in the registry (entries' .addr
    values and macro arguments alike): blocks end at them."""
    if not path or not path.exists():
        return set()
    out = set()
    for m in re.finditer(r"\b0x([0-9A-Fa-f]{6})\b", path.read_text(encoding="utf-8")):
        a = int(m.group(1), 16)
        if bus_to_offset(a) is not None or a >> 17 == 0x3F:
            out.add(a)
    return out


def shard_of(addr: int, shards: int) -> int:
    """Stable across analysis changes: a change to one routine only touches the
    shards holding its kilobyte of address space."""
    return ((addr >> 10) * 2654435761 & 0xFFFFFFFF) % shards


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def byte_array(name: str, data: bytes) -> list[str]:
    out = [f"const uint8_t {name}[{max(len(data), 1)}] = {{"]
    for k in range(0, len(data), 24):
        out.append("    " + ",".join(f"0x{b:02X}" for b in data[k:k + 24]) + ",")
    return out + ["};"]


def ram_section_table(an: Analyzer, masks: dict) -> list[str]:
    """generated_ram_sections[]: the RAM sections' names, run addresses and images, and
    the images and guard masks the blocks' guards compare with."""
    out = [""]
    for i, sec in enumerate(an.ram.sections):
        out += byte_array(f"generated_ram_image_{i}", sec.image)
        out += byte_array(f"generated_ram_mask_{i}", bytes(masks.get(i, bytes(len(sec.image)))))
    out += [f"const int generated_ram_section_count = {len(an.ram.sections)};",
            "const GeneratedRamSection generated_ram_sections[] = {"]
    for i, sec in enumerate(an.ram.sections):
        out.append(f'    {{ "{sec.name}", 0x{sec.base:06X}, {len(sec.image)}, generated_ram_image_{i} }},')
    if not an.ram.sections:
        out.append("    { 0 },")
    out.append("};")
    return out


def index_key(pc: int, ctx) -> int:
    """pc | P's M and X bits << 24 | E << 30, as the runtime forms it (native.c)."""
    return pc | (0x20 if ctx.m8 else 0) << 24 | (0x10 if ctx.x8 else 0) << 24 | (1 << 30 if ctx.e else 0)


def instruction_index(blocks: list) -> list[str]:
    """generated_index[]: for every instruction of every block, a block that can start
    there (its function starts where PC points), sorted by address and widths, so
    the runtime can continue in generated code at any instruction it reaches: where
    a block stopped, or a computed jump target. One block per instruction for ROM
    code (the one entered there if any), one per RAM section for RAM code."""
    best = {}
    for b in blocks:
        for pc, s in b.steps.items():
            key = (index_key(pc, s.ctx), b.space)
            cur = best.get(key)
            if cur is None or (cur.entry != pc and (b.entry == pc or b.entry < cur.entry)):
                best[key] = b
    out = ["", f"const int generated_index_count = {len(best)};", "const GeneratedIndexEntry generated_index[] = {"]
    for (key, space), b in sorted(best.items(), key=lambda kv: kv[0]):
        out.append(f'    {{ 0x{key:08X}, {b.name}, {b.guard or "NULL"}, "{b.name}" }},')
    if not best:
        out.append("    { 0 },")
    return out + ["};"]


def generate(rom: Rom, hints: Path, registry: Path, coverage: list, calls: list, out: Path, shards: int,
             crc: int) -> dict:
    t0 = time.time()
    an = Analyzer(rom, hints_mod.load(hints), coverage=coverage_mod.load(coverage))
    an.run()
    t1 = time.time()
    call_targets = set(coverage_mod.load_calls(calls)) if calls else set()
    builder = BlockBuilder(an, registry_addresses(registry), call_targets)
    blocks = builder.build_all()
    t2 = time.time()
    # MD4: the code set of the blocks is the analysis's, which the matching source
    # writes as instructions (docs/MATCHING.md): every instruction variant in a
    # block is analysed code, and every analysed variant is in a block.
    generated = {(pc, s.ctx.m8, s.ctx.x8) for b in blocks for pc, s in b.steps.items()}
    analysed = code_set(an)
    if generated != analysed:
        extra, missing = sorted(generated - analysed), sorted(analysed - generated)
        sys.exit(f"generate: the blocks' code set differs from the analysis's: {len(extra)} variants only in blocks "
                 f"{[f'{a:06X}' for a, _, _ in extra[:5]]}, {len(missing)} only in the analysis "
                 f"{[f'{a:06X}' for a, _, _ in missing[:5]]}")

    out.mkdir(parents=True, exist_ok=True)
    files = [[] for _ in range(shards)]
    for b in blocks:
        files[shard_of(b.entry, shards)].append(b)
    changed = 0
    insns = 0
    externs = [f"extern const uint8_t generated_ram_image_{i}[], generated_ram_mask_{i}[];"
               for i in range(len(an.ram.sections))]
    for i, shard in enumerate(files):
        lines = HEADER + ['#include "port/generated_block.h"', "", *externs, ""]
        for b in shard:
            insns += len(b.steps)
            lines += indent(builder.emit(b), 0)
            lines.append("")
        changed += write_if_changed(out / f"blocks_{i:03d}.c", "\n".join(lines) + "\n")

    table = HEADER + ['#include "port/generated_table.h"', ""]
    table += [f"void {b.name}(Snes *s);" for b in blocks]
    table += [f"bool {b.guard}(Snes *s);" for b in blocks if b.guard]
    table += ["", f"const uint32_t generated_rom_crc = 0x{crc:08X};",
              f"const int generated_native_count = {len(blocks)};",
              "const NativeEntry generated_natives[] = {"]
    for b in blocks:
        p = (0x20 if b.ctx.m8 else 0) | (0x10 if b.ctx.x8 else 0)
        extra = (f", .guard = {b.guard}" if b.guard else "") + (", .emulation = true" if b.ctx.e else "")
        table.append(f'    {{ .addr = 0x{b.entry:06X}, .name = "{b.name}", .fn = {b.name}, '
                     f'.p_mask = 0x{0 if b.ctx.e else 0x30:02X}, .p_value = 0x{0 if b.ctx.e else p:02X}, '
                     f'.generated = true{extra} }},')
    if not blocks:
        table.append("    { 0 },")
    table.append("};")
    table += instruction_index(blocks)
    table += ram_section_table(an, builder.masks)
    changed += write_if_changed(out / "table.c", "\n".join(table) + "\n")
    return {"analysis_s": t1 - t0, "blocks_s": t2 - t1, "write_s": time.time() - t2, "blocks": len(blocks),
            "instructions": insns, "analysis_instructions": sum(len(v) for v in an.code.values()),
            "code_set": len(analysed),
            "files_changed": changed}


def main():
    ap = argparse.ArgumentParser(prog="python3 -m tools.generate")
    ap.add_argument("--rom", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--hints", type=Path, default=Path("re/hints.toml"))
    ap.add_argument("--registry", type=Path, default=Path("game/registry.c"))
    ap.add_argument("--coverage", type=Path, action="append", default=[])
    ap.add_argument("--calls", type=Path, action="append", default=[])
    ap.add_argument("--shards", type=int, default=64)
    ap.add_argument("--stamp", type=Path, help="file to touch when done (build systems)")
    args = ap.parse_args()

    data = args.rom.read_bytes()
    if len(data) % 0x8000 == 0x200:
        data = data[0x200:]
    crc = zlib.crc32(data)
    if crc != ROM_CRC32:
        sys.exit(f"{args.rom}: CRC32 {crc:08X}, expected {ROM_CRC32:08X} (Chrono Trigger (USA))")
    stats = generate(Rom(data), args.hints, args.registry, args.coverage, args.calls, args.out, args.shards, crc)
    print("generate: {blocks} blocks, {instructions} instructions ({analysis_instructions} in the analysis; "
          "code set of {code_set} instruction variants, the same in blocks and analysis); "
          "analysis {analysis_s:.1f} s, blocks {blocks_s:.1f} s, write {write_s:.1f} s; "
          "{files_changed} files changed".format(**stats))
    if args.stamp:
        args.stamp.parent.mkdir(parents=True, exist_ok=True)
        args.stamp.write_text("", encoding="utf-8")


if __name__ == "__main__":
    main()
