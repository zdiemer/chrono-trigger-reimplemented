"""Generate C blocks for every statically found code block of the ROM.

    python3 -m tools.recomp --rom roms/ct-usa.sfc --out build/main/recomp \\
        [--hints re/hints.toml] [--registry game/registry.c] \\
        [--coverage traces/coverage.txt ...] [--calls traces/calls.txt ...] [--shards 64]

Runs the disassembler's analysis in process (hints, coverage seeds), forms
blocks (tools/recomp/blocks.py) and writes blocks_000.c ... blocks_NNN.c and
table.c into --out. Output is ROM-derived: it belongs in the build tree only.
Files whose content didn't change aren't rewritten, so the build only
recompiles what changed. See docs/RECOMP.md.
"""

import argparse
import re
import sys
import time
import zlib
from pathlib import Path

from tools.disasm import coverage as coverage_mod
from tools.disasm import hints as hints_mod
from tools.disasm.analyze import Analyzer
from tools.disasm.memmap import Rom, bus_to_offset

from .blocks import BlockBuilder
from .translate import indent

ROM_CRC32 = 0x2D206BF7
HEADER = ["/* Generated by tools/recomp from the ROM (docs/RECOMP.md). ROM-derived: never commit. */"]


def registry_addresses(path: Path) -> set:
    """Every 24-bit ROM address named in the registry (entries' .addr values and
    macro arguments alike): blocks end at them."""
    if not path or not path.exists():
        return set()
    out = set()
    for m in re.finditer(r"\b0x([0-9A-Fa-f]{6})\b", path.read_text(encoding="utf-8")):
        a = int(m.group(1), 16)
        if bus_to_offset(a) is not None:
            out.add(a)
    return out


def shard_of(addr: int, shards: int) -> int:
    """Stable across analysis changes: a change to one routine only touches the
    shards holding its kilobyte of address space."""
    return ((addr >> 10) * 2654435761 & 0xFFFFFFFF) % shards


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def generate(rom: Rom, hints: Path, registry: Path, coverage: list, calls: list, out: Path, shards: int,
             crc: int) -> dict:
    t0 = time.time()
    an = Analyzer(rom, hints_mod.load(hints), coverage=coverage_mod.load(coverage))
    an.run()
    t1 = time.time()
    call_targets = set(coverage_mod.load_calls(calls)) if calls else set()
    builder = BlockBuilder(an, registry_addresses(registry), call_targets)
    blocks = builder.build_all()
    t2 = time.time()

    out.mkdir(parents=True, exist_ok=True)
    files = [[] for _ in range(shards)]
    for b in blocks:
        files[shard_of(b.entry, shards)].append(b)
    changed = 0
    insns = 0
    for i, shard in enumerate(files):
        lines = HEADER + ['#include "port/recomp_block.h"', ""]
        for b in shard:
            insns += len(b.steps)
            lines += indent(builder.emit(b), 0)
            lines.append("")
        changed += write_if_changed(out / f"blocks_{i:03d}.c", "\n".join(lines) + "\n")

    table = HEADER + ['#include "port/recomp_table.h"', ""]
    table += [f"void {b.name}(Snes *s);" for b in blocks]
    table += ["", f"const uint32_t recomp_rom_crc = 0x{crc:08X};",
              f"const int recomp_native_count = {len(blocks)};",
              "const NativeEntry recomp_natives[] = {"]
    for b in blocks:
        p = (0x20 if b.ctx.m8 else 0) | (0x10 if b.ctx.x8 else 0)
        table.append(f'    {{ .addr = 0x{b.entry:06X}, .name = "{b.name}", .fn = {b.name}, '
                     f'.p_mask = 0x30, .p_value = 0x{p:02X}, .generated = true }},')
    if not blocks:
        table.append("    { 0 },")
    table.append("};")
    changed += write_if_changed(out / "table.c", "\n".join(table) + "\n")
    return {"analysis_s": t1 - t0, "blocks_s": t2 - t1, "write_s": time.time() - t2, "blocks": len(blocks),
            "instructions": insns, "analysis_instructions": sum(len(v) for v in an.code.values()),
            "files_changed": changed}


def main():
    ap = argparse.ArgumentParser(prog="python3 -m tools.recomp")
    ap.add_argument("--rom", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--hints", type=Path, default=Path("re/hints.toml"))
    ap.add_argument("--registry", type=Path, default=Path("game/registry.c"))
    ap.add_argument("--coverage", type=Path, action="append", default=[])
    ap.add_argument("--calls", type=Path, action="append", default=[])
    ap.add_argument("--shards", type=int, default=64)
    ap.add_argument("--stamp", type=Path, help="file to touch when done (build systems)")
    args = ap.parse_args()

    data = args.rom.read_bytes()
    if len(data) % 0x8000 == 0x200:
        data = data[0x200:]
    crc = zlib.crc32(data)
    if crc != ROM_CRC32:
        sys.exit(f"{args.rom}: CRC32 {crc:08X}, expected {ROM_CRC32:08X} (Chrono Trigger (USA))")
    stats = generate(Rom(data), args.hints, args.registry, args.coverage, args.calls, args.out, args.shards, crc)
    print("recomp: {blocks} blocks, {instructions} instructions ({analysis_instructions} in the analysis); "
          "analysis {analysis_s:.1f} s, blocks {blocks_s:.1f} s, write {write_s:.1f} s; "
          "{files_changed} files changed".format(**stats))
    if args.stamp:
        args.stamp.parent.mkdir(parents=True, exist_ok=True)
        args.stamp.write_text("", encoding="utf-8")


if __name__ == "__main__":
    main()
