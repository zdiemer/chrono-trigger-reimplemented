"""Naive split of the ROM into source (docs/MATCHING.md, MD0).

Code the analysis found becomes instructions in the dialect of
tools/matching/asm.py; instructions that overlap another instruction or decode
with different lengths under different widths become `db` with a label at
every instruction start; every other byte is an `incbin` of a file extracted
from the ROM, cut and named by jump tables and typed [[data]] hints. An
[[overlap]] hint picks the decode written where an instruction really runs with
two lengths. check_coverage and check_data are MD1's checks on the result.
Works on bytes and an Analyzer that has run, so tests can use synthetic code;
tools/matching/__main__.py runs it on the real ROM.

Operands are symbolic where the analysis already knows the target is code or a
table: branches, `PER`, `JSR`/`JMP abs` and `(abs,X)`, `JSL`/`JML long`.
Everything else stays a number until MD3.
"""

import bisect
import re
from collections import Counter, defaultdict
from dataclasses import dataclass, field

from tools.disasm.analyze import Analyzer, describe_widths
from tools.disasm.cpu import OPCODES, Mode, decode
from tools.disasm.battlescript import FORMATS as SCRIPT_FORMATS, ScriptError, context as script_context,     decode as script_decode, encode as script_encode
from tools.disasm.memmap import bus_to_offset, fmt
from tools.disasm import eventscript
from tools.disasm.dataformats import event_bytes, event_entries
from tools.disasm.text import FORMATS as TEXT_FORMATS, TextError, decode as text_decode, \
    dictionary_context, encode as text_encode, parse_dictionary_text, region_params

HEADER = "; Generated by tools.matching from the ROM (docs/MATCHING.md). ROM-derived: never commit."
BANK = 0x10000
DB_PER_LINE = 16
DATA_DIR = "data/raw"

_M = Mode
OPERAND_FORMAT = {
    _M.DP: "{}", _M.DPX: "{},X", _M.DPY: "{},Y", _M.DPIND: "({})", _M.DPXIND: "({},X)",
    _M.DPINDY: "({}),Y", _M.DPLIND: "[{}]", _M.DPLINDY: "[{}],Y", _M.PEI: "({})",
    _M.SR: "{},S", _M.SRINDY: "({},S),Y",
    _M.ABS: "{}", _M.ABSX: "{},X", _M.ABSY: "{},Y", _M.ABSIND: "({})", _M.ABSXIND: "({},X)",
    _M.ABSLIND: "[{}]", _M.PEA: "{}", _M.LONG: "{}", _M.LONGX: "{},X",
}
_NAME_OK = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
RESERVED = {name for name, _ in OPCODES} | {"A", "X", "Y", "S"}


def insn_line(name: str, mode: Mode, size: int, operand: int, ref: str | None = None) -> str:
    """An instruction in the dialect. `ref` replaces the address operand with a
    label (required for branches and PER, whose operand is a target)."""
    n = size - 1
    if mode is Mode.IMP:
        return name
    if mode is Mode.ACC:
        return f"{name} A"
    if mode in (Mode.REL8, Mode.REL16):
        if ref is None:
            raise ValueError(f"{name} needs a label target")
        return f"{name} {ref}"
    if mode is Mode.MOVE:
        dst, src = operand & 0xFF, operand >> 8
        return f"{name} ${src:02X},${dst:02X}"
    sfx = ".b" if n == 1 else ".w" if n == 2 else ".l"
    if mode in (Mode.IMM_M, Mode.IMM_X, Mode.IMM8):
        return f"{name}{sfx} #${operand:0{2 * n}X}"
    return f"{name}{sfx} " + OPERAND_FORMAT[mode].format(ref or f"${operand:0{2 * n}X}")


def width_note(widths_set) -> tuple:
    """Joint (m, x) over an instruction's variants, 8/16 or None (unknown or mixed)."""
    ms = {w[0] for w in widths_set}
    xs = {w[1] for w in widths_set}
    m = None if len(ms) != 1 or None in ms else (8 if True in ms else 16)
    x = None if len(xs) != 1 or None in xs else (8 if True in xs else 16)
    return m, x


def note_text(note: tuple) -> str:
    return ";@ m{} x{}".format(*("?" if v is None else v for v in note))


@dataclass
class Stats:
    insn_bytes: int = 0
    insns: int = 0
    db_bytes: int = 0
    db_regions: int = 0
    incbin_bytes: int = 0
    incbin_files: int = 0
    labels: int = 0
    unplaced: list = field(default_factory=list)          # (name, offset) inside an instruction
    registry_not_insn: list = field(default_factory=list)  # registry addresses not an instruction start
    overlap_problems: list = field(default_factory=list)   # alternates of overlap hints that don't fit
    blob_kinds: list = field(default_factory=lambda: [Counter() for _ in range(64)])  # incbin bytes by kind
    untyped_blobs: list = field(default_factory=list)       # (bus address, size) with no type
    per_bank: list = field(default_factory=lambda: [[0, 0, 0] for _ in range(64)])  # insn, db, incbin
    text_regions: Counter = field(default_factory=Counter)   # format -> regions assembled from text
    text_bytes: Counter = field(default_factory=Counter)     # format -> their bytes
    text_problems: list = field(default_factory=list)        # regions of a text format kept raw, and why
    event_streams: int = 0          # lz regions of an event format written decoded beside their bytes
    event_bytes: int = 0            # their decompressed bytes


@dataclass
class CoverageCheck:
    rom: int = 0                  # executed ROM addresses
    ok: int = 0                   # of those, instruction starts with compatible widths
    ram: int = 0                  # executed addresses outside ROM (checked against RAM sections)
    problems: list = field(default_factory=list)   # (bus address, text)


class Emitter:
    def __init__(self, data: bytes, an: Analyzer, registry: dict | None = None, call_targets=()):
        self.data = data
        self.an = an
        self.registry = registry or {}          # bus addr -> [names]
        self.call_targets = set(call_targets)
        self.stats = Stats()

    # ---- layout ---------------------------------------------------------------

    def layout(self):
        by_off = defaultdict(list)
        for pc, variants in self.an.code.items():
            off = bus_to_offset(pc)
            if off is None:                    # RAM sections are emitted separately
                continue
            for widths, insn in variants.items():
                by_off[off].append((pc, widths, insn))
        # An `overlap` hint names the widths whose decode is written as
        # instructions where others decode with another length; those others
        # are alternates, checked to end on an instruction boundary.
        self.alternates = {}             # offset -> [(pc, widths, insn)] not written
        for addr, widths in self.an.hints.overlaps.items():
            off = bus_to_offset(addr)
            vs = by_off.get(off)
            if not vs:
                continue
            primary = [v for v in vs if v[1] == widths]
            if primary:
                size = primary[0][2].size
                by_off[off] = [v for v in vs if v[2].size == size]
                self.alternates[off] = [v for v in vs if v[2].size != size]
        starts = sorted(by_off)
        self.clean = {}                  # offset -> [(pc, widths, insn)]
        self.clusters = {}               # start -> (end, member offsets)
        self.owner = {}                  # offset strictly inside a clean instruction -> its start
        i = 0
        while i < len(starts):
            s = starts[i]
            end = s + max(v[2].size for v in by_off[s])
            members = [s]
            j = i + 1
            while j < len(starts) and starts[j] < end:
                members.append(starts[j])
                end = max(end, starts[j] + max(v[2].size for v in by_off[starts[j]]))
                j += 1
            if len(members) == 1 and len({v[2].size for v in by_off[s]}) == 1:
                self.clean[s] = sorted(by_off[s], key=lambda v: (v[0] < 0xC00000, v[0], str(v[1])))
                for k in range(s + 1, end):
                    self.owner[k] = s
            else:
                self.clusters[s] = (end, members)
            i = j
        self.by_off = by_off
        self.stats.overlap_problems = []
        for off, alts in sorted(self.alternates.items()):
            for pc, w, insn in alts:
                end = off + insn.size
                if off not in self.clean or not (end in self.clean or end % BANK == 0):
                    self.stats.overlap_problems.append(
                        f"{fmt(pc)} [{describe_widths(w)}] {insn.text()} doesn't end on an instruction boundary")

    # ---- labels ---------------------------------------------------------------

    def assign_labels(self):
        explicit = defaultdict(list)
        for addr, name in sorted(self.an.hints.names.items()):
            off = bus_to_offset(addr)
            if off is not None:
                explicit[off].append(name)
        for addr in sorted(self.registry):
            off = bus_to_offset(addr)
            if off is not None:
                explicit[off].extend(self.registry[addr])
        generated = {}
        prio = {"sub": 0, "jt": 1, "loc": 2}
        for addr, kinds in self.an.labels.items():
            off = bus_to_offset(addr)
            if off is None or not kinds:
                continue
            kind = min(kinds, key=prio.get)
            if off not in generated or prio[kind] < prio.get(generated[off], 3):
                generated[off] = kind
        for addr in self.call_targets:
            off = bus_to_offset(addr)
            if off is not None and (off in self.clean or off in self.clusters):
                generated[off] = "sub"
        for s, (end, members) in self.clusters.items():
            for o in members:
                generated.setdefault(o, "loc")
        # Data regions from [[data]] hints: the hint's name, else type_ADDRESS.
        for r in self.an.hints.data_regions:
            off = bus_to_offset(r.start)
            if off is None:
                continue
            if r.name:
                explicit[off].append(r.name)
            else:
                generated.setdefault(off, r.type or "data")
        # Targets of branches and PER must be labels.
        for off, variants in self.clean.items():
            for pc, _, insn in variants:
                if insn.mode in (Mode.REL8, Mode.REL16):
                    t = bus_to_offset(insn.branch_target())
                    if t is not None:
                        generated.setdefault(self.owner.get(t, t), "loc")

        self.names = {}          # offset -> [names], the first used in operands
        self.unplaced_at = {}
        used = {}
        for off in sorted(set(explicit) | set(generated)):
            cands = []
            for nm in explicit.get(off, []):
                nm = nm if _NAME_OK.match(nm) else re.sub(r"\W", "_", nm)
                if nm.upper() in RESERVED:
                    nm += "_"
                if nm not in cands:
                    cands.append(nm)
            if not cands:
                cands = [f"{generated[off]}_{0xC00000 | off:06X}"]
            final = []
            for nm in cands:
                if nm in used and used[nm] != off:
                    nm = f"{nm}_{0xC00000 | off:06X}"
                if nm not in used:
                    used[nm] = off
                    final.append(nm)
            if off in self.owner:
                self.stats.unplaced.extend((nm, off) for nm in final)
                self.unplaced_at[off] = final
                for nm in final:
                    del used[nm]
                continue
            self.names[off] = final
        self.stats.labels = sum(len(v) for v in self.names.values())
        for addr in sorted(self.registry):
            off = bus_to_offset(addr)
            if off is not None and off not in self.clean:
                self.stats.registry_not_insn.append(addr)

    def ref(self, addr: int) -> str | None:
        off = bus_to_offset(addr)
        names = self.names.get(off) if off is not None else None
        return names[0] if names else None

    # ---- instructions -----------------------------------------------------------

    def render(self, off: int) -> str | None:
        """The instruction at a clean offset, or None if it can't be written
        symbolically (a branch whose target has no label)."""
        pc, _, insn = self.clean[off][0]
        name, mode, v = insn.name, insn.mode, insn.operand
        ref = None
        if mode in (Mode.REL8, Mode.REL16):
            t_off = bus_to_offset(insn.branch_target())
            if t_off is None or t_off >> 16 != off >> 16:
                return None
            start = self.owner.get(t_off, t_off)     # PER can point inside an instruction
            if start not in self.names:
                return None
            ref = self.names[start][0] + (f"+{t_off - start}" if t_off != start else "")
        elif (name, mode) in (("JSR", Mode.ABS), ("JMP", Mode.ABS), ("JSR", Mode.ABSXIND), ("JMP", Mode.ABSXIND)):
            t = (pc & 0xFF0000) | v
            t_off = bus_to_offset(t)
            if t_off is not None and t_off >> 16 == off >> 16 and (mode is Mode.ABS or t_off in self.names):
                ref = self.ref(t)
        elif (name, mode) in (("JSL", Mode.LONG), ("JML", Mode.LONG)):
            t_off = bus_to_offset(v)
            if t_off is not None and 0xC00000 | t_off == v:
                ref = self.ref(v)
        return insn_line(name, mode, insn.size, v, ref)

    # ---- emission ---------------------------------------------------------------

    def build(self) -> dict:
        """Returns {relative path: text or bytes} for the source tree."""
        self.layout()
        self.assign_labels()
        ctx_at = defaultdict(set)
        for (entry, widths), c in self.an.contexts.items():
            off = bus_to_offset(entry)
            if off is not None:
                at = "" if entry == 0xC00000 | off else f" at {fmt(entry)}"
                ctx_at[off].add(f"{describe_widths(widths)}{at} ({', '.join(sorted(c.kinds))})")
        self.index_data()
        self.text_jobs = {}                      # .bin path -> (.txt path, region)
        self.event_jobs = {}                     # .txt path -> the decompressed stream it must encode to
        try:
            self.text_context = dictionary_context(self.an.hints.data_regions, self.data, bus_to_offset)
        except TextError as exc:
            self.text_context = {}
            self.stats.text_problems.append(f"the dialog dictionary: {exc}")
        stops = sorted(set(self.clean) | set(self.clusters) | set(self.names)
                       | set(range(0, len(self.data), BANK)) | set(self.data_cuts))
        files = {}
        st = self.stats
        top = [HEADER, "", "hirom", ""]
        for bank_off in range(0, len(self.data), BANK):
            bank = 0xC0 + (bank_off >> 16)
            end_of_bank = bank_off + BANK
            lines = []
            note = None
            o = bank_off
            while o < end_of_bank:
                if o in ctx_at:
                    lines.append("")
                    lines.append(f"; {fmt(0xC00000 | o)} entered " + "; ".join(sorted(ctx_at[o])))
                for nm in self.names.get(o, ()):
                    lines.append(f"{nm}:")
                if o in self.clean:
                    variants = self.clean[o]
                    text = self.render(o)
                    insn = variants[0][2]
                    if text is not None:
                        wn = width_note({w for _, w, _ in variants})
                        if wn != note:
                            lines.append(note_text(wn))
                            note = wn
                        where = fmt(0xC00000 | o)
                        mirrors = sorted({pc for pc, _, _ in variants if pc != 0xC00000 | o})
                        if mirrors:
                            where += " (runs at " + ", ".join(fmt(p) for p in mirrors) + ")"
                        lines.append(f"\t{text:<31} ; {where}")
                        for pc, w, alt in self.alternates.get(o, ()):
                            lines.append(f"; {fmt(pc)} also runs as [{describe_widths(w)}] {alt.text()}, "
                                         f"{alt.size} bytes up to {fmt(0xC00000 | o + alt.size)} (overlap hint)")
                        st.insns += 1
                        st.insn_bytes += insn.size
                        st.per_bank[bank_off >> 16][0] += insn.size
                    else:
                        lines.append(f"; {fmt(0xC00000 | o)} {insn.text()}: target has no label, as data")
                        self._db(lines, o, o + insn.size)
                        st.db_regions += 1
                        note = None
                    for uo in range(o + 1, o + insn.size):
                        for nm in self.unplaced_at.get(uo, ()):
                            lines.append(f"; ({nm} would be at {fmt(0xC00000 | uo)}, inside this instruction)")
                    o += insn.size
                    continue
                if o in self.clusters:
                    end, members = self.clusters[o]
                    lines.append(f"; {fmt(0xC00000 | o)}-{fmt(0xC00000 | end - 1)}: instructions that overlap "
                                 "or change length with the widths, as data:")
                    for mo in members:
                        for pc, w, insn in sorted(self.by_off[mo], key=lambda v: (v[0], str(v[1]))):
                            lines.append(f";   {fmt(pc)} [{describe_widths(w)}] {insn.text()}")
                    st.db_regions += 1
                    cut = [mo for mo in range(o + 1, end) if mo in self.names]
                    prev = o
                    for c in cut + [end]:
                        if prev != o:
                            for nm in self.names[prev]:
                                lines.append(f"{nm}:")
                        self._db(lines, prev, c)
                        prev = c
                    note = None
                    o = end
                    continue
                nxt = min(stops[bisect.bisect_right(stops, o)] if bisect.bisect_right(stops, o) < len(stops)
                          else len(self.data), end_of_bank)
                kind, region = self.blob_kind(o)
                if region is not None:
                    r_off = bus_to_offset(region.start)
                    label = self.names.get(r_off, [f"data_{region.start:06X}"])[0]
                    part = "" if o == r_off else f"_{0xC00000 | o:06X}"
                    path = f"data/{region.type or 'untyped'}/{label}{part}.bin"
                else:
                    path = f"{DATA_DIR}/bank_{bank:02X}/{0xC00000 | o:06X}.bin"
                text = self._decoded(region, o, nxt) if region is not None else None
                if text is not None:
                    # Assembled from its decoded form: encode_text() writes
                    # the .bin from the .txt as it reads back from disk.
                    files[path[:-4] + ".txt"] = text
                    self.text_jobs[path] = (path[:-4] + ".txt", region)
                else:
                    files[path] = self.data[o:nxt]
                    event = self._decoded_stream(region, o, nxt) if region is not None else None
                    if event is not None:
                        # A compressed script: the stream is assembled as bytes
                        # (nothing recompresses), and its output written decoded
                        # beside it; encode_text() checks that it encodes back.
                        files[path[:-4] + ".txt"] = event[0]
                        self.event_jobs[path[:-4] + ".txt"] = event[1]
                lines.append(f'\tincbin "{path}" ; {fmt(0xC00000 | o)}-{fmt(0xC00000 | nxt - 1)}, {nxt - o} bytes'
                             + ("" if kind == "untyped" else f", {kind}"))
                st.incbin_files += 1
                st.incbin_bytes += nxt - o
                st.per_bank[bank_off >> 16][2] += nxt - o
                st.blob_kinds[bank_off >> 16][kind] += nxt - o
                if kind == "untyped":
                    st.untyped_blobs.append((0xC00000 | o, nxt - o))
                note = None
                o = nxt
            counts = st.per_bank[bank_off >> 16]
            head = [HEADER, f"; Bank ${bank:02X}, file offset ${bank_off:06X}-${end_of_bank - 1:06X} (HiROM): "
                    f"{counts[0]} bytes of instructions, {counts[1]} bytes of db, {counts[2]} bytes of incbin",
                    "", f"org ${bank:02X}0000"]
            tail = ["", f"warnpc ${bank + 1:02X}0000"] if bank < 0xFF else []
            files[f"bank_{bank:02X}.asm"] = "\n".join(head + lines + tail) + "\n"
            top.append(f'incsrc "bank_{bank:02X}.asm"')
        files["rom.asm"] = "\n".join(top) + "\n"
        return files

    # ---- data regions -----------------------------------------------------------

    def index_data(self):
        """Offsets where blobs are cut (every jump table and [[data]] region starts
        and ends on one), and lookups for what a blob is."""
        spans = []                                   # (start, end exclusive, kind, region)
        for jt in self.an.tables.values():
            o = bus_to_offset(jt.table)
            if o is not None and jt.count:
                spans.append((o, o + jt.count * (3 if jt.kind == "long" else 2), "jump table", None))
        for r in self.an.hints.data_regions:
            o = bus_to_offset(r.start)
            if o is not None:
                spans.append((o, bus_to_offset(r.end) + 1, r.type or "untyped hint", r))
        spans.sort(key=lambda s: (s[0], s[2] != "jump table"))
        self.data_spans = spans
        self._span_starts = [s[0] for s in spans]
        self.data_cuts = {s[0] for s in spans} | {s[1] for s in spans}

    def blob_kind(self, off: int) -> tuple:
        """(kind, DataHint or None) for the blob starting at off: the jump table or
        [[data]] region containing it, else "untyped"."""
        i = bisect.bisect_right(self._span_starts, off)
        best = ("untyped", None)
        for s, e, kind, region in reversed(self.data_spans[max(0, i - 64):i]):
            if s <= off < e:
                if kind == "jump table":
                    return kind, None
                best = (kind, region)
        return best

    def _decoded(self, region, start: int, end: int) -> str | None:
        """The readable form of a whole region of a text format
        (tools/disasm/text.py), or None to extract it raw (a region cut into
        parts by a label inside it, or bytes the format rejects, which
        check_data reports)."""
        form = region.params.get("format")
        commands = region.type == "script" and form == "event-commands"
        script = region.type == "script" and form in SCRIPT_FORMATS
        if not commands and not script and (region.type != "text" or form not in TEXT_FORMATS):
            return None
        where = f"{fmt(region.start)}-{fmt(region.end)} ({form})"
        if start != bus_to_offset(region.start) or end != bus_to_offset(region.end) + 1:
            self.stats.text_problems.append(f"{where}: cut by a label inside it, extracted raw")
            return None
        try:
            if commands:
                text = eventscript.decode_commands(self.data[start:end], event_entries(region))
            elif script:
                text = script_decode(form, self.data[start:end], region, self.script_context())
            else:
                text = text_decode(form, self.data[start:end], region_params(region), self.text_context)
        except (TextError, ScriptError, eventscript.ScriptError) as exc:
            self.stats.text_problems.append(f"{where}: {exc}")
            return None
        self.stats.text_regions[form] += 1
        self.stats.text_bytes[form] += end - start
        return text if text.endswith("\n") else text + "\n"

    def _decoded_stream(self, region, start: int, end: int):
        """(readable form, decompressed bytes) of a whole `lz` region of an
        event format, or None (tools/disasm/eventscript.py). A stream that
        doesn't decode is check_data's to report."""
        if region.type != "lz" or region.params.get("format") not in eventscript.LZ_FORMATS:
            return None
        if start != bus_to_offset(region.start) or end != bus_to_offset(region.end) + 1:
            return None
        try:
            raw = event_bytes(self.data[start:end], region)
            text = eventscript.decode(raw)
        except (ValueError, eventscript.ScriptError):
            return None
        self.stats.event_streams += 1
        self.stats.event_bytes += len(raw)
        return text, raw

    def script_context(self) -> dict:
        """What the battle script formats need from the whole ROM
        (tools/disasm/battlescript.py), worked out once."""
        if getattr(self, "_script_context", None) is None:
            self._script_context = script_context(self.data)
        return self._script_context

    def encode_text(self, src) -> tuple[dict, list]:
        """The .bin of every region build() wrote as text, encoded from the
        .txt as it reads back from `src` (the dictionary first, since dialog
        needs it); and every compressed event script's decoded output encoded
        back and compared with the stream's. Returns ({path: bytes}, problems)."""
        out, problems = {}, []
        context = {}
        jobs = sorted(self.text_jobs.items(), key=lambda j: j[1][1].params.get("format") != "dialog-dictionary")
        for path, (txt, region) in jobs:
            form = region.params["format"]
            try:
                text = (src / txt).read_bytes().decode("utf-8")
                if form == "event-commands":
                    out[path] = eventscript.encode(text)
                    continue
                if form in SCRIPT_FORMATS:
                    out[path] = script_encode(form, text, region)
                    continue
                if form == "dialog-dictionary":
                    context["dictionary"] = parse_dictionary_text(text)
                out[path] = text_encode(form, text, region_params(region), context)
            except (OSError, UnicodeDecodeError, TextError, ScriptError, eventscript.ScriptError) as exc:
                problems.append(f"{txt}: {exc}")
        for txt, raw in sorted(self.event_jobs.items()):
            try:
                if eventscript.encode((src / txt).read_bytes().decode("utf-8")) != raw:
                    problems.append(f"{txt}: doesn't encode to the stream's output")
            except (OSError, UnicodeDecodeError, eventscript.ScriptError) as exc:
                problems.append(f"{txt}: {exc}")
        return out, problems

    def check_data(self) -> list:
        """Problems with [[data]] regions: overlap with instructions or with each
        other, and regions whose bytes don't have their type's shape."""
        from tools.disasm.lz import stream_length
        from tools.disasm.dataformats import check_format
        problems = []
        try:
            context = dictionary_context(self.an.hints.data_regions, self.data, bus_to_offset)
        except TextError as exc:
            problems.append(f"the dialog dictionary: {exc}")
            context = {}
        if any(r.type == "script" and r.params.get("format") in SCRIPT_FORMATS for r in self.an.hints.data_regions):
            context.update(self.script_context())
        code = set()
        for off in self.clean:
            code.update(range(off, off + self.clean[off][0][2].size))
        for end, members in self.clusters.values():
            code.update(range(members[0], end))
        prev = None
        for r in self.an.hints.data_regions:
            s, e = bus_to_offset(r.start), bus_to_offset(r.end) + 1
            where = f"{fmt(r.start)}-{fmt(r.end)} ({r.type})"
            if prev is not None and s < prev[1]:
                problems.append(f"{where} overlaps {fmt(0xC00000 | prev[0])}")
            prev = (s, e)
            inside = [o for o in range(s, e) if o in code]
            if inside:
                problems.append(f"{where} holds instructions from {fmt(0xC00000 | inside[0])}")
            blob = self.data[s:e]
            n = e - s
            size = {"words": 2, "ptr16": 2, "ptr24": 3}.get(r.type) or (r.params.get("size") if r.type == "struct"
                                                                           else None)
            if r.type == "padding" and len(set(blob)) != 1:
                problems.append(f"{where} isn't one fill value")
            elif size and n % size:
                problems.append(f"{where}: {n} bytes isn't a multiple of {size}")
            elif r.type == "lz" and stream_length(self.data, s) != n:
                problems.append(f"{where}: the decompressor doesn't consume exactly these bytes")
            try:
                check_format(blob, r, context)
            except (ValueError, KeyError) as exc:
                problems.append(f"{where}: {exc}")
        return problems

